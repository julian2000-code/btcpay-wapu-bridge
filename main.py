"""
SatTope — Lightning payment layer for Argentine merchants.

Flow:
1. Customer pays Lightning invoice generated by phoenixd
2. Sats land in merchant's phoenixd wallet
3. Merchant decides when to convert sats → USDT via WapuPay
4. Merchant withdraws USDT → ARS → Mercado Pago when ready
"""

import json
import logging
import os
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
from pydantic import BaseModel

from phoenixd import (create_phoenixd_invoice, get_phoenixd_balance,
                      get_phoenixd_invoice, list_phoenixd_payments,
                      pay_phoenixd_invoice)
from wapu import create_lightning_invoice, get_transaction, get_transactions, get_wapu_home

load_dotenv()

logging.basicConfig(level=logging.INFO, format="%(asctime)s  %(levelname)s  %(message)s")
logger = logging.getLogger(__name__)

WAPU_WITHDRAW_ALIAS = os.getenv("WAPU_WITHDRAW_ALIAS", "")
WITHDRAWALS_FILE = Path("data/withdrawals.json")

app = FastAPI(
    title="SatTope",
    description="Lightning payment layer for Argentine merchants.",
    version="2.0.0"
)
app.mount("/static", StaticFiles(directory="static"), name="static")
templates = Jinja2Templates(directory="templates")


# --- Local storage helpers ---

def _load_withdrawals() -> list:
    if not WITHDRAWALS_FILE.exists():
        return []
    with open(WITHDRAWALS_FILE) as f:
        return json.load(f)


def _save_withdrawals(withdrawals: list):
    WITHDRAWALS_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(WITHDRAWALS_FILE, "w") as f:
        json.dump(withdrawals, f, indent=2)


